import pandas as pd
import numpy as np
import math

def entropy(target_col):
    values, counts = np.unique(target_col, return_counts=True)
    probs = counts / counts.sum()
    return -sum(p * math.log2(p) for p in probs if p > 0)

def info_gain(data, split_attr, target_name):
    total_entropy = entropy(data[target_name])
    values, counts = np.unique(data[split_attr], return_counts=True)
    weighted_entropy = sum(
        (counts[i] / counts.sum()) * entropy(data[data[split_attr] == values[i]][target_name])
        for i in range(len(values))
    )
    return total_entropy - weighted_entropy

def id3(data, original_data, features, target_name, parent_class=None):
    if len(np.unique(data[target_name])) <= 1:
        return np.unique(data[target_name])[0]
    if len(data) == 0:
        return np.unique(original_data[target_name])[
            np.argmax(np.unique(original_data[target_name], return_counts=True)[1])
        ]
    if len(features) == 0:
        return parent_class

    parent_class = np.unique(data[target_name])[
        np.argmax(np.unique(data[target_name], return_counts=True)[1])
    ]

    gains = [info_gain(data, feature, target_name) for feature in features]
    best_feature = features[np.argmax(gains)]

    tree = {best_feature: {}}
    remaining_features = [f for f in features if f != best_feature]

    for value in np.unique(data[best_feature]):
        sub_data = data[data[best_feature] == value]
        subtree = id3(sub_data, data, remaining_features, target_name, parent_class)
        tree[best_feature][value] = subtree

    return tree

def predict(query, tree, default='Yes'):
    for attribute in query:
        if attribute in tree:
            try:
                result = tree[attribute][query[attribute]]
            except KeyError:
                return default
            if isinstance(result, dict):
                return predict(query, result, default)
            else:
                return result
    return default

