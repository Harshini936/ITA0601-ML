import pandas as pd
import numpy as np

def candidate_elimination(csv_path):
    data = pd.read_csv(csv_path)
    print("Training data:")
    print(data)

    concepts = data.iloc[:, :-1].values
    target = data.iloc[:, -1].values

    n_attributes = concepts.shape[1]

    specific_h = list(concepts[0])
    general_h = [['?' for _ in range(n_attributes)] for _ in range(n_attributes)]

    for i, instance in enumerate(concepts):
        if target[i].strip().lower() == 'yes':
            for x in range(n_attributes):
                if instance[x] != specific_h[x]:
                    specific_h[x] = '?'
                    general_h[x][x] = '?'
        else:
            for x in range(n_attributes):
                if instance[x] != specific_h[x]:
                    general_h[x][x] = specific_h[x]
                else:
                    general_h[x][x] = '?'

    general_h = [h for h in general_h if h != ['?'] * n_attributes]

    return specific_h, general_h

